"""Vector figure and example-record listing for the paper, from the release files.

Writes paper/generated/fig_years.pdf (mapped vulnerabilities per publication year by
severity; hatched for grayscale) and paper/generated/example_record.tex.
Usage: python code/figures.py
"""
import json
from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("pdf")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "paper/generated"
SEVS = [("CRITICAL", "#202020", ""), ("HIGH", "#606060", "//"), ("MEDIUM", "#a0a0a0", ".."),
        ("LOW", "#d8d8d8", ""), ("", "white", "xx")]


def main() -> None:
    fixes = json.loads((ROOT / "data/release/iotsecfix_fixes.json").read_text())
    per_vuln = {}
    for f in fixes:
        per_vuln.setdefault(f["vuln_id"], f)
    counts = Counter((v["published"][:4], v["severity"] if v["severity"] in
                      ("CRITICAL", "HIGH", "MEDIUM", "LOW") else "")
                     for v in per_vuln.values() if v["published"])
    years = sorted({y for y, _ in counts})
    plt.rcParams.update({"font.size": 7, "pdf.fonttype": 42, "hatch.linewidth": 0.5})
    fig, ax = plt.subplots(figsize=(3.4, 1.6))
    bottom = [0] * len(years)
    for sev, color, hatch in SEVS:
        h = [counts.get((y, sev), 0) for y in years]
        ax.bar(years, h, bottom=bottom, color=color, hatch=hatch, edgecolor="black",
               linewidth=0.4, label=sev.title() if sev else "No score")
        bottom = [b + x for b, x in zip(bottom, h)]
    ax.set_ylabel("Vulnerabilities")
    ax.tick_params(axis="x", rotation=90)
    ax.legend(ncol=5, fontsize=6, frameon=False, loc="upper left", handlelength=1.2,
              columnspacing=0.8)
    ax.set_ylim(0, max(bottom) * 1.25)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(pad=0.2)
    GEN.mkdir(parents=True, exist_ok=True)
    fig.savefig(GEN / "fig_years.pdf")

    # example: the earliest-published zephyr record linked by both an NVD commit URL and code scope
    ex = sorted((f for f in fixes if f["project"] == "zephyr" and "nvd_ref" in f["link_sources"]
                 and f["change_scope"] == "code" and f["cwe_ids"] and f["published"]),
                key=lambda f: (f["published"], f["fix_commit"]))[0]
    keep = ["vuln_id", "cwe_ids", "severity", "cvss_score", "published", "fix_commit",
            "parent_commits", "commit_date", "files_changed", "lines_added", "lines_deleted",
            "fix_to_publication_days", "tiers", "link_sources", "change_scope"]
    body = []
    for k in keep:
        v = ex[k]
        if k in ("fix_commit", "parent_commits"):
            v = v[:12] + "..."
        body.append(f'  "{k}": {json.dumps(v)},')
    body[-1] = body[-1].rstrip(",")
    (GEN / "example_record.tex").write_text(
        "% GENERATED by code/figures.py. Do not edit.\n\\begin{verbatim}\n{\n" + "\n".join(body)
        + "\n}\n\\end{verbatim}\n")
    print("example:", ex["vuln_id"], ex["fix_commit"])


if __name__ == "__main__":
    main()
